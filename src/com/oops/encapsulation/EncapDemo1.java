package com.oops.encapsulation;

public class EncapDemo1 {
	private int sid;
	private String name;
	private int age;

	public void setSid(int sid){
		this.sid=sid;
	}
	public int getSid() {
		return sid;
	}
	public void setName(String name) {
		this.name=name;
	}
	public String getName() {
		return name;
	}
	public void setAge(int age) {
		this.age=age;
	}
	public int getAge() {
		return age;
	}
	

}
